    /** Orthogonal to the  basis of the evaluation domain, the polynomials can be represented in a way that allows for efficient computation
     * a monomial basis or the lch basis**/
    enum class polynomial_basis_config : std::uint8_t
    {
        monomial_poly_basis = 0,
        lch_poly_basis = 1,
    };

    inline polynomial_basis_config &polynomial_basis_storage()
    {
        thread_local polynomial_basis_config v = polynomial_basis_config::monomial_poly_basis;
        return v;
    }

    inline void set_polynomial_basis_config(polynomial_basis_config impl)
    {
        polynomial_basis_storage() = impl;
    }

    inline polynomial_basis_config get_polynomial_basis_config()
    {
        return polynomial_basis_storage();
    }

